/**
 * Turn the engine's grammar and lexer into a syntax-only checker's sources.
 *
 *   node build/generate.mjs <tesseractdb>/src/parser <outdir>
 *
 * Writes `check_grammar.y` and `check_lexer.l` to `outdir`:
 *
 * - The grammar is the engine's own rules with every C action taken out:
 *   nothing is built, a statement is only accepted or rejected. Precedence
 *   choices (`%dprec`) stay, and so does the one action that steers the lexer
 *   (`match_patterns_count`, which changes how `-` and `[` read inside a MATCH
 *   pattern).
 * - The lexer is the engine's own rules, unchanged, with a small stand-in for
 *   the parser context they reach into (see shim.h), and comment hints
 *   recognised from the engine's own hint table.
 *
 * Used by build/build.mjs; not meant to be run on its own.
 */
import fs from 'node:fs';
import path from 'node:path';

export function generate(srcDir, outDir) {
  const G = fs.readFileSync(path.join(srcDir, 'corasql_grammar.y'), 'utf8');
  const L = fs.readFileSync(path.join(srcDir, 'corasql_lexer.l'), 'utf8');

  // --- grammar ----------------------------------------------------------------
  const sections = G.split(/^%%/m);
  if (sections.length < 3) throw new Error('corasql_grammar.y: expected %% sections.');
  const [decl, rules, epilogue] = sections;

  const tokenLines = [...decl.matchAll(/^%token\s*(?:<[^>]*>)?\s*(.*)$/gm)]
    .map((m) => m[1].replace(/\/\*.*?\*\//g, '').trim())
    .filter(Boolean)
    .map((t) => `%token ${t}`);

  const bare = stripActions(rules).replace(/\n\s*\n+/g, '\n');

  const grammar = `/* Generated by CoraDB-SQLSyntaxChecker-Wasm build/generate.mjs from corasql_grammar.y: the engine's rules, no actions. */
%code requires {
typedef struct CORASQL_YYLTYPE {
  int first_line, first_column, last_line, last_column, buffer_pos;
} CORASQL_YYLTYPE;
#define CORASQL_YYLTYPE_IS_DECLARED 1
#define CORASQL_YYLTYPE_IS_TRIVIAL 1
}
%code {
#include <stdlib.h>
#include <string.h>
int corasql_yylex (void);
void corasql_yyerror (const char *s);
extern int match_patterns_count;
}
%define api.prefix {corasql_yy}
%locations
%glr-parser
%define parse.error verbose
%union { int number; char *cptr; }
${tokenLines.join('\n')}
%%
${bare}
%%
`;
  fs.writeFileSync(path.join(outDir, 'check_grammar.y'), grammar);

  // --- lexer ------------------------------------------------------------------
  const lparts = L.split(/^%%/m);
  if (lparts.length < 3) throw new Error('corasql_lexer.l: expected %% sections.');
  const [ldecl, lrules] = lparts;
  const opts = [...ldecl.matchAll(/^%(?:option|x|s)\b.*$/gm)].map((m) => m[0]).join('\n');
  const outside = ldecl.replace(/^%\{[\s\S]*?^%\}/gm, '').replace(/\/\*[\s\S]*?\*\//g, '');
  const defs = outside
    .split('\n')
    .filter((l) => /^[A-Za-z_][A-Za-z0-9_]*\s+\S/.test(l))
    .join('\n');
  const hints = [...epilogue.matchAll(/\{"([A-Z_]+)",\s*NULL,\s*PT_HINT_/g)].map((m) => m[1]);
  if (hints.length === 0) throw new Error('corasql_grammar.y: the hint table was not found.');

  fs.writeFileSync(path.join(outDir, 'check_lexer.l'), lexerSource(opts, defs, lrules, hints));
  return { tokens: tokenLines.length, hints: hints.length };
}

/** Remove comments and { } actions from the rules; keep the one that steers the lexer. */
function stripActions(text) {
  let out = '';
  const n = text.length;
  const skipQuoted = (j) => {
    const q = text[j];
    let k = j + 1;
    while (k < n && text[k] !== q) k += text[k] === '\\' ? 2 : 1;
    return k + 1;
  };
  for (let i = 0; i < n; ) {
    const c = text[i];
    if (text.startsWith('/*', i)) {
      const j = text.indexOf('*/', i + 2);
      i = j < 0 ? n : j + 2;
      out += ' ';
      continue;
    }
    if (text.startsWith('//', i)) {
      const j = text.indexOf('\n', i);
      i = j < 0 ? n : j;
      continue;
    }
    if (c === '"' || c === "'") {
      const j = skipQuoted(i);
      out += text.slice(i, j);
      i = j;
      continue;
    }
    if (c === '{') {
      let depth = 0;
      let j = i;
      while (j < n) {
        if (text.startsWith('/*', j)) {
          const k = text.indexOf('*/', j + 2);
          j = k < 0 ? n : k + 2;
          continue;
        }
        const ch = text[j];
        if (ch === '"' || ch === "'") {
          j = skipQuoted(j);
          continue;
        }
        if (ch === '{') depth += 1;
        else if (ch === '}') {
          depth -= 1;
          if (depth === 0) break;
        }
        j += 1;
      }
      const body = text.slice(i, j + 1);
      out += body.includes('match_patterns_count -= 1') ? ' { match_patterns_count -= 1; } ' : ' ';
      i = j + 1;
      continue;
    }
    out += c;
    i += 1;
  }
  return out;
}

function lexerSource(opts, defs, rules, hints) {
  const hintList = hints.map((h) => `"${h}"`).join(', ');
  return `/* Generated by CoraDB-SQLSyntaxChecker-Wasm build/generate.mjs from corasql_lexer.l: the engine's lexer rules. */
%{
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <strings.h>
#include "check_grammar.tab.h"
#include "shim.h"
#define CORASQL_MAXNAME 256
static char *parser_c_hint (void);
static char *parser_line_hint (void);
static void begin_token (char *token);
int yycolumn = 1, yycolumn_end = 1;
int dot_flag = 0;
int match_patterns_count = 0;
int str_identifier = '\\0';
int yybuffer_pos = 0;
#undef YY_INPUT
#define YY_INPUT(buf, result, max) { result = check_input (buf, max); }
#define YY_USER_ACTION { yybuffer_pos += corasql_yyget_leng (); corasql_yylloc.buffer_pos = yybuffer_pos; }
#define IS_BLANK_CHAR(c) ((c) == ' ' || (c) == '\\t' || (c) == '\\r' || (c) == '\\n')
/* Characters the hint readers give back are taken off the count again. */
#define UNPUT_COUNTED(ch) do { int ch_ = (ch); if (ch_ > 0) { unput (ch_); yybuffer_pos--; } } while (0)
%}
%option noyywrap never-interactive
${opts}
${defs}
%%
${rules}
%%
static const char *const hint_names[] = { ${hintList}, 0 };

static int
is_word_char (char c)
{
  return c == '_' || (c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z') || (c >= '0' && c <= '9');
}

/* Like the engine's pt_check_hint: a "+" comment is a hint when it names one. */
static int
is_hint (const char *text)
{
  for (int k = 0; hint_names[k]; k++)
    {
      size_t n = strlen (hint_names[k]);
      for (const char *p = text; *p; p++)
        if (strncasecmp (p, hint_names[k], n) == 0
            && (p == text || !is_word_char (p[-1])) && !is_word_char (p[n]))
          return 1;
    }
  return 0;
}

/*
 * A character read past flex, by the hint readers. Counted into
 * yybuffer_pos, which is how far into the text the lexer is: the engine kept
 * that count by hand in each reader; here it is kept in one place.
 */
static int
input_internal (void)
{
  int c = input ();
  if (c > 0)
    yybuffer_pos++;
  if (c == '\\n')
    {
      this_parser->line = corasql_yylloc.last_line = yylineno;
      this_parser->column = corasql_yylloc.last_column = yycolumn_end = 1;
    }
  else
    this_parser->column = corasql_yylloc.last_column = yycolumn_end++;
  return c;
}

static char *
parser_c_hint (void)
{
  int c, c1;
  char buff[CORASQL_MAXNAME];
  int i = 0;
  yycolumn = yycolumn_end;
  corasql_yylloc.first_column = yycolumn;
  corasql_yylloc.first_line = corasql_yylloc.last_line = yylineno;
  corasql_yylloc.last_column = yycolumn_end;
  if ((c = input_internal ()) == '+')
    {
      buff[i++] = '+';
      while ((c = input_internal ()) != 0 && c != -1)
        {
          if (c == '*')
            {
              c1 = input_internal ();
              if (c1 == '/')
                break;
              UNPUT_COUNTED (c1);
            }
          if (i >= CORASQL_MAXNAME - 1)
            goto consume_comment;
          buff[i++] = c;
        }
      buff[i] = 0;
      return is_hint (buff) ? pt_makename (buff) : NULL;
    }
  else
    UNPUT_COUNTED (c);
consume_comment:
  while ((c = input_internal ()) != '*' && c != 0 && c != -1)
    ;
  if (c == 0 || c == -1)
    return NULL;
  if ((c1 = input_internal ()) != '/' && c1 != 0 && c1 != -1)
    {
      UNPUT_COUNTED (c1);
      goto consume_comment;
    }
  return NULL;
}

static char *
parser_line_hint (void)
{
  int c;
  char buff[CORASQL_MAXNAME];
  int i = 0;
  yycolumn = yycolumn_end;
  corasql_yylloc.first_column = yycolumn;
  corasql_yylloc.first_line = corasql_yylloc.last_line = yylineno;
  corasql_yylloc.last_column = yycolumn_end;
  if ((c = input_internal ()) == '+')
    {
      buff[i++] = '+';
      while ((c = input_internal ()) != '\\r' && c != '\\n' && c != 0 && c != -1)
        if (i < CORASQL_MAXNAME - 1)
          buff[i++] = c;
      buff[i] = 0;
      return is_hint (buff) ? pt_makename (buff) : NULL;
    }
  UNPUT_COUNTED (c);
  while ((c = input_internal ()) != '\\r' && c != '\\n' && c != 0 && c != -1)
    ;
  return NULL;
}

static void
begin_token (char *token)
{
  yycolumn = yycolumn_end;
  yycolumn_end += strlen (token);
  corasql_yylloc.first_line = yylineno;
  corasql_yylloc.first_column = yycolumn;
  corasql_yylloc.last_line = yylineno;
  corasql_yylloc.last_column = yycolumn_end;
}

void
check_reset_lexer (void)
{
  yycolumn = yycolumn_end = 1;
  dot_flag = 0;
  match_patterns_count = 0;
  yybuffer_pos = 0;
  yylineno = 1;
  BEGIN (INITIAL);
  corasql_yyrestart (NULL);
}

const char *
check_token_text (void)
{
  return corasql_yyget_text ();
}
`;
}
